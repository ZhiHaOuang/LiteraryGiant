import assert from 'node:assert/strict'
import {writeFileSync} from 'node:fs'
const {_electron}=await import(process.env.LG_PLAYWRIGHT_MODULE)
const stage=process.env.LG_PAGES_TEST_ROOT
assert.ok(stage?.includes('LitIsLand/lg-pages-'),'Use an isolated multipage fixture profile')
const app=await _electron.launch({executablePath:process.env.LG_PAGES_APP??'/Applications/LiteraryGiant.app/Contents/MacOS/LiteraryGiant',args:['--user-data-dir='+stage+'/userData'],env:{...process.env,DSH_HOME:stage+'/home'},timeout:30000})
let page
try {
 page=await app.firstWindow();page.setDefaultTimeout(15000)
 const errors=[];page.on('pageerror',e=>{errors.push(e.message);console.log(e.stack)})

 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1500,1050))
 await page.locator('[data-lg-pages]').waitFor()

 await page.getByRole('button',{name:'在“潮汐来信”中新建会话',exact:true}).click()
 await page.locator('[data-lg-page]:visible button[aria-haspopup="menu"]').filter({hasText:'潮汐来信'}).waitFor()
 const firstPage=page.locator('[data-lg-page]:visible').filter({has:page.locator('[data-composer-input]')}).filter({hasText:'潮汐来信'})
 await firstPage.locator('[data-composer-input]').fill('潮汐来信的独立Draft——不要发送')
 const firstId=await firstPage.getAttribute('data-lg-page')
 let first=page.locator(`[data-lg-page="${firstId}"] [data-composer-input]`)
 const sessionId=await firstPage.locator('[data-conversation-session]').getAttribute('data-conversation-session')
 await page.getByRole('button',{name:'Global Dashboard',exact:true}).first().click({button:'right'})
 await page.getByRole('menuitem',{name:'打开方式',exact:true}).hover()
 await page.getByRole('menuitem',{name:'分栏打开',exact:true}).click()
 await page.getByRole('button',{name:'在“山间来客”中新建会话',exact:true}).click()
 await page.locator('[data-lg-page]:visible button[aria-haspopup="menu"]').filter({hasText:'山间来客'}).waitFor()
 const secondPage=page.locator('[data-lg-page]:visible').filter({has:page.locator('[data-composer-input]')}).filter({hasText:'山间来客'})
 await secondPage.locator('[data-composer-input]').fill('山间来客的独立Draft——不要发送')
 const secondId=await secondPage.getAttribute('data-lg-page')
 const second=page.locator(`[data-lg-page="${secondId}"] [data-composer-input]`)
 const ids=await page.locator('[data-lg-page]:visible [data-conversation-session]').evaluateAll(es=>es.map(e=>e.getAttribute('data-conversation-session')))
 assert.equal(new Set(ids).size,2)
 assert.ok((await first.innerText()).includes('潮汐来信的独立Draft'))
 await first.click()
 await page.getByRole('button',{name:'Global Dashboard',exact:true}).click()
 await page.locator('[data-lg-page-title]:visible').filter({hasText:'Global Dashboard'}).waitFor()
 assert.ok(await second.isVisible())
 assert.equal(await page.locator(`[data-lg-page="${firstId}"]`).count(),0)
 assert.equal(await page.locator('[data-lg-page]').count(),2)
 await page.locator(`[data-row-key="session:${sessionId}"]`).click()
 first=page.locator(`[data-conversation-session="${sessionId}"] [data-composer-input]`)
 await first.waitFor({state:'visible'})
 assert.ok((await first.innerText()).includes('潮汐来信的独立Draft'))
 assert.ok((await second.innerText()).includes('山间来客的独立Draft'))
 const heights=await page.locator('[data-lg-pages] [data-dockkit-pane]').evaluateAll(es=>es.map(e=>e.getBoundingClientRect().height/window.innerHeight))
 assert.equal(heights.length,2)
 const headerHeights=await page.locator('[data-lg-pane-header]').evaluateAll(es=>es.map(e=>({height:e.getBoundingClientRect().height,fade:getComputedStyle(e,'::after').height})))
 assert.ok(headerHeights.every(h=>h.height===50&&h.fade==='24px'))
 assert.equal(await page.locator('[data-lg-page-title][aria-haspopup]').count(),0)
 assert.ok(heights.every(h=>h>0.8),'both panes fill the available window height')
 await page.screenshot({path:stage+'/two-conversations.png'})
 await app.evaluate(({nativeTheme})=>{nativeTheme.themeSource='dark'})
 await page.emulateMedia({colorScheme:'dark'})
 await page.waitForFunction(()=>document.documentElement.style.colorScheme==='dark')
 await page.screenshot({path:stage+'/two-conversations-dark.png'})
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1100,850))
 await page.screenshot({path:stage+'/two-conversations-narrow.png'})
 await first.fill('');await second.fill('')
 await page.locator('[data-dockkit-pane][data-dockkit-column="0"]:visible').getByRole('button',{name:'关闭当前栏',exact:true}).click()
 assert.equal(await page.locator('[data-lg-page]:visible').count(),1)
 assert.deepEqual(errors,[])
 writeFileSync(stage+'/two-conversations-result.json',JSON.stringify({independentSessions:ids,independentDrafts:true,focusTargetsSidebar:true,pageErrors:errors},null,2))
 console.log('PASS two cross-book conversations, separate drafts, focus navigation, light/dark and narrow layouts')
} catch(error){if(page){await page.screenshot({path:stage+'/two-conversations-failure.png'});console.log((await page.locator('body').innerText()).slice(-2300))}throw error}
finally{await app.close()}
