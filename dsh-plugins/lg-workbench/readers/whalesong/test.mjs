import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
const {chromium} = await import(process.env.LG_PLAYWRIGHT_MODULE)
const browser = await chromium.launch({executablePath:process.env.LG_CHROMIUM_EXECUTABLE,headless:true})
try {
  const page = await browser.newPage({viewport:{width:1100,height:800}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.setContent('<iframe sandbox="allow-scripts" style="border:0;width:100%;height:780px"></iframe>')
  await page.evaluate(html=>{window.messages=[];window.addEventListener('message',e=>window.messages.push(e.data));document.querySelector('iframe').srcdoc=html},await readFile('preview.html','utf8'))
  await page.waitForFunction(()=>window.messages.some(m=>m.type==='lg-reader:ready'))
  const data={type:'lg-reader:chapter',chapterId:'chapter-01',title:'第一章 · 雨落长街',bookTitle:'合成测试书',chapterIndex:1,text:Array.from({length:65},(_,i)=>`第${i+1}段。雨落在长街上，远处的灯亮了。她把旧信轻轻放下，转身走向门边。`).join('\n\n')}
  const send=async(value)=>page.evaluate(v=>document.querySelector('iframe').contentWindow.postMessage(v,'*'),value)
  await send(data)
  const frame=page.frameLocator('iframe')
  await frame.getByRole('heading',{name:data.title,exact:true}).waitFor()
  assert.equal(await frame.locator('.nv-reader-page p').count(),65)
  const before=await frame.locator('.nv-reader-page').evaluate(e=>getComputedStyle(e).fontSize)
  await frame.getByTitle('放大字号',{exact:true}).click()
  assert.equal(await frame.locator('.nv-reader-page').evaluate(e=>getComputedStyle(e).fontSize),`${parseInt(before)+1}px`)
  await frame.getByLabel('纸张',{exact:true}).selectOption('night')
  assert.equal(await frame.locator('.nv-reader').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(20, 21, 26)')
  await frame.getByLabel('纸张',{exact:true}).selectOption('paper')
  await frame.locator('.nv-reader-scroll').evaluate(e=>e.scrollTop=500)
  await send(data)
  assert.equal(await frame.locator('.nv-reader-scroll').evaluate(e=>e.scrollTop),500)
  await page.screenshot({path:'wide.png'})
  await page.setViewportSize({width:390,height:800})
  assert.ok(await frame.locator('.nv-reader-scroll').evaluate(e=>e.scrollWidth<=e.clientWidth+1))
  await page.screenshot({path:'narrow.png'})
  await send({...data,chapterId:'chapter-02',title:'第二章',chapterIndex:2,text:'新章节正文。🙂 测试 Unicode。'})
  await frame.getByRole('heading',{name:'第二章',exact:true}).waitFor()
  assert.equal(await frame.locator('.nv-reader-page p').count(),1)
  assert.equal(await frame.locator('.nv-reader-scroll').evaluate(e=>e.scrollTop),0)
  assert.deepEqual(errors,[])
  console.log('PASS: original ReaderPage in sandbox, 65 paragraphs, font/theme, duplicate message, chapter switch, 390px, no JS errors')
} finally {await browser.close()}
