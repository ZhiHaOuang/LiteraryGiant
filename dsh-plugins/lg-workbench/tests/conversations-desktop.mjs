import assert from 'node:assert/strict'
import {writeFileSync} from 'node:fs'
const {_electron}=await import(process.env.LG_PLAYWRIGHT_MODULE)
const stage=process.env.LG_PAGES_TEST_ROOT
assert.ok(stage?.includes('LitIsLand/lg-pages-'),'Use an isolated multipage fixture profile')
const app=await _electron.launch({executablePath:'/Applications/LiteraryGiant.app/Contents/MacOS/LiteraryGiant',args:['--user-data-dir='+stage+'/userData'],env:{...process.env,DSH_HOME:stage+'/home'},timeout:30000})
let page
try {
 page=await app.firstWindow();page.setDefaultTimeout(15000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1500,1050))
 await page.locator('[data-lg-pages]').waitFor()
 await page.getByRole('button',{name:'在“潮汐来信”中新建会话',exact:true}).click()
 const firstPage=page.locator('[data-lg-page]:visible').filter({hasText:'潮汐来信'})
 await firstPage.locator('[data-composer-input]').fill('潮汐来信的独立草稿——不要发送')
 const firstId=await firstPage.getAttribute('data-lg-page')
 const existing=await page.locator('[data-dockkit-tab-close]').evaluateAll(es=>es.map(e=>e.getAttribute('data-dockkit-tab-close')))
 for(const id of existing)if(id!==firstId){await page.locator(`[data-dockkit-tab="${id}"]`).click();await page.locator(`[data-dockkit-tab-close="${id}"]`).click()}
 await page.locator(`[data-dockkit-tab="${firstId}"]`).click()
 const first=page.locator(`[data-lg-page="${firstId}"] [data-composer-input]`)
 await page.getByRole('button',{name:'左右分栏',exact:true}).click()
 await page.getByRole('button',{name:'在“山间来客”中新建会话',exact:true}).click()
 const secondPage=page.locator('[data-lg-page]:visible').filter({hasText:'山间来客'})
 await secondPage.locator('[data-composer-input]').fill('山间来客的独立草稿——不要发送')
 const secondId=await secondPage.getAttribute('data-lg-page')
 const second=page.locator(`[data-lg-page="${secondId}"] [data-composer-input]`)
 const ids=await page.locator('[data-lg-page]:visible [data-conversation-session]').evaluateAll(es=>es.map(e=>e.getAttribute('data-conversation-session')))
 assert.equal(new Set(ids).size,2)
 assert.ok((await first.innerText()).includes('潮汐来信的独立草稿'))
 await first.click()
 await page.getByRole('button',{name:'书架总览',exact:true}).click()
 await page.getByRole('heading',{name:'全局 Dashboard',exact:true}).waitFor()
 assert.ok(await second.isVisible())
 assert.ok(!(await first.isVisible()))
 await page.locator(`[data-dockkit-tab="${firstId}"]`).click()
 await first.waitFor({state:'visible'})
 assert.ok((await first.innerText()).includes('潮汐来信的独立草稿'))
 assert.ok((await second.innerText()).includes('山间来客的独立草稿'))
 const heights=await page.locator('[data-lg-pages] [data-dockkit-pane]').evaluateAll(es=>es.map(e=>e.getBoundingClientRect().height/window.innerHeight))
 assert.equal(heights.length,2)
 assert.ok(heights.every(h=>h>0.8),'both panes fill the available window height')
 await page.screenshot({path:stage+'/two-conversations.png'})
 await app.evaluate(({nativeTheme})=>{nativeTheme.themeSource='dark'})
 await page.emulateMedia({colorScheme:'dark'})
 await page.waitForFunction(()=>document.documentElement.style.colorScheme==='dark')
 await page.screenshot({path:stage+'/two-conversations-dark.png'})
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1100,850))
 await page.screenshot({path:stage+'/two-conversations-narrow.png'})
 await first.fill('');await second.fill('')
 assert.deepEqual(errors,[])
 writeFileSync(stage+'/two-conversations-result.json',JSON.stringify({independentSessions:ids,independentDrafts:true,focusTargetsSidebar:true,pageErrors:errors},null,2))
 console.log('PASS two cross-book conversations, separate drafts, focus navigation, light/dark and narrow layouts')
} catch(error){if(page){await page.screenshot({path:stage+'/two-conversations-failure.png'});console.log((await page.locator('body').innerText()).slice(-2300))}throw error}
finally{await app.close()}
