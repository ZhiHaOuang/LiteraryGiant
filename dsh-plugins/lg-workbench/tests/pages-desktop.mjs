import assert from 'node:assert/strict'
import {writeFileSync} from 'node:fs'
const {_electron}=await import(process.env.LG_PLAYWRIGHT_MODULE)
const stage=process.env.LG_PAGES_TEST_ROOT
assert.ok(stage?.includes('LitIsLand/lg-pages-'),'Use an isolated multipage fixture profile')
const app=await _electron.launch({executablePath:'/Applications/LiteraryGiant.app/Contents/MacOS/LiteraryGiant',args:['--user-data-dir='+stage+'/userData'],env:{...process.env,DSH_HOME:stage+'/home'},timeout:30000})
let page
try{
 page=await app.firstWindow();page.setDefaultTimeout(15000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1500,1050))
 await page.locator('[data-lg-pages]').waitFor()
 await page.getByRole('button',{name:'书架总览',exact:true}).click()
 await page.getByRole('button',{name:'左右分栏',exact:true}).click()
 await page.getByRole('button',{name:'文学编辑台',exact:true}).click()
 await page.getByLabel('作品',{exact:true}).selectOption({label:'潮汐来信'})
 await page.getByLabel('待编辑文本',{exact:true}).waitFor()
 const chapter=page.getByLabel('待编辑文本',{exact:true})
 const original=await chapter.inputValue()
 await chapter.fill(original+'未保存分栏测试')
 await page.screenshot({path:stage+'/two-pages-light.png'})
 assert.equal(await page.getByRole('heading',{name:'全局 Dashboard',exact:true}).count(),1)
 const rightId=await chapter.evaluate(e=>e.closest('[data-lg-page]').dataset.lgPage)
 const right=page.locator(`[data-dockkit-content="${rightId}"]`)
 assert.equal(await right.getByRole('button',{name:'关闭标签',exact:true}).count(),0)
 await page.getByRole('button',{name:'书架总览',exact:true}).click()
 assert.equal(await page.getByRole('heading',{name:'全局 Dashboard',exact:true}).count(),2)
 await page.getByRole('tab',{name:/潮汐来信/}).click()
 assert.equal(await chapter.inputValue(),original+'未保存分栏测试')
 await page.getByRole('button',{name:'放弃未保存编辑',exact:true}).click()
 await page.getByRole('button',{name:'阅读对照',exact:true}).click()
 await page.locator('.lgr-trial iframe').waitFor()
 await page.getByRole('button',{name:'展开阅读',exact:true}).click()
 const bounds=await page.locator('.lgr-expanded').boundingBox()
 const global=await page.getByRole('heading',{name:'全局 Dashboard',exact:true}).boundingBox()
 assert.ok(bounds.x>global.x+global.width,'expanded reader stays inside its pane')
 await page.getByRole('button',{name:'收起阅读',exact:true}).click()
 await page.screenshot({path:stage+'/two-pages-reader.png'})
 await page.getByRole('heading',{name:'全局 Dashboard',exact:true}).click()
 await page.getByRole('button',{name:'文学编辑台',exact:true}).click()
 const chooser=page.locator('[data-lg-page]:visible').filter({hasText:'请选择作品，再打开需要阅读或编辑的章节'})
 await chooser.getByLabel('作品',{exact:true}).selectOption({label:'潮汐来信'})
 await chooser.waitFor({state:'hidden'})
 assert.equal(await page.getByRole('tab',{name:/潮汐来信/}).count(),1)
 await page.getByRole('heading',{name:'全局 Dashboard',exact:true}).click()
 await page.getByRole('button',{name:'文学编辑台',exact:true}).click()
 await chooser.getByLabel('作品',{exact:true}).selectOption({label:'山间来客'})
 const other=page.locator('[data-lg-page]:visible').filter({has:page.getByLabel('作品',{exact:true}).locator('option:checked').filter({hasText:'山间来客'})})
 await other.getByLabel('待编辑文本',{exact:true}).waitFor()
 assert.equal(await page.locator('[data-lg-page]:visible .lgw-page').count(),2)
 await other.getByLabel('作品',{exact:true}).selectOption({label:'潮汐来信'})
 await other.getByLabel('作品',{exact:true}).locator('option:checked').filter({hasText:'山间来客'}).waitFor({state:'attached'})
 assert.equal(await page.getByRole('tab',{name:/潮汐来信/}).count(),1)
 await page.screenshot({path:stage+'/two-books.png'})
 writeFileSync(stage+'/two-pages-result.json',JSON.stringify({twoPanes:true,focusedNavigation:true,draftRetained:true,lockedClose:true,readerContained:true,chapterDedup:true,crossBookEditors:true,errors},null,2))
 assert.deepEqual(errors,[])
 console.log('PASS two panes, focused sidebar, draft retention reader containment, chapter dedup and cross-book editors')
}catch(e){if(page){await page.screenshot({path:stage+'/two-pages-failure.png'});console.log((await page.locator('body').innerText()).slice(0,1800))}throw e}
finally{await app.close()}
